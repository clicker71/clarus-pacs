//! Deletion cascade: a study takes its derived objects with it.
//!
//! Three wire gates over a real server and real fixtures:
//!
//! 1. Deleting a study removes the workitem named from it and every
//!    presentation state and segmentation that references into it.
//! 2. Deleting one series leaves the derived objects of the study's other
//!    series alone: an annotation of a different series is not part of this
//!    series and must survive it.
//! 3. Re-stowing a deleted study recreates its workitem, so deleting a study
//!    does not permanently disable the CAD step for the study UID.
//!
//! The derived fixtures are generated by `tests/make_derived_fixtures.py` and
//! committed, so these tests run against the bytes a real producer wrote
//! rather than against a shape built to match the reader.

#![forbid(unsafe_code)]

