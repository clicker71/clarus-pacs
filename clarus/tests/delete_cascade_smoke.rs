// -- The study and series the fixtures annotate --------------------------
//
// The series and instance UIDs are named by the committed fixtures; the tests
// substitute them in place (see `reidentify`), so only the study is a literal
// here.
const STUDY_A: &str = "1.2.826.0.1.3680043.10.1709.1";

/// Series B of the same study, which the PR fixture does NOT reference.
///
/// The series-scoped gate deletes this one and asserts the derived objects -
/// which point at series A - are untouched.
const SERIES_B: &str = "1.2.826.0.1.3680043.10.1709.1.2";

/// The PR fixture's OWN study and series, as `make_derived_fixtures.py` writes
/// them. A derived object lives in its own study, so moving one to another
/// study means rewriting all three UIDs.
const PR_STUDY: &str = "1.2.826.0.1.3680043.10.1709.2.1";
const PR_SERIES: &str = "1.2.826.0.1.3680043.10.1709.2.9";
const PR_INSTANCE: &str = "1.2.826.0.1.3680043.10.1709.2.1.1";

/// The series and instance the PR fixture references inside its annotation.
const REF_SERIES_A: &str = "1.2.826.0.1.3680043.10.1709.1.1";
const REF_INSTANCE_A: &str = "1.2.826.0.1.3680043.10.1709.1.1.1";

/// The CAD workitem UID for a study.
///
/// Asked from the server rather than recomputed here: the point of the
/// cascade is that it uses the server's own derivation, so a test that
/// re-derived it would not notice the cascade drifting away from it.
///
/// A study yields ONE workitem per catalog entry, and the entry set depends on
/// the study's Modality. The committed fixtures are CT, so this resolves the
/// CT entry through the very config the harness boots with - the UID comes
/// from the server's rule rather than from a code value spelled out here.
/// `catalog_for_modality` is asserted below to have exactly one entry, so a
/// shipped table that started offering CT two codes would fail loudly here
/// instead of making these tests read an arbitrary one.
fn workitem_uid(study: &str) -> String {
    let ups = Config::test_default().ups;
    let codes = ups.catalog_for_modality(Some("CT"));
    assert_eq!(
        codes.len(),
        1,
        "these fixtures are CT and the shipped table gives CT one code; got {codes:?}"
    );
    clarus_server::handlers::cad_workitem::workitem_uid_for_study_code(study, codes[0])
}

// -- Test server harness -------------------------------------------------

struct TestServer {
    addr: SocketAddr,
    _temp: tempfile::TempDir,
    manifest_dir: PathBuf,
    state: Arc<AppState>,
}

impl TestServer {
    fn start() -> Self {
        let temp = tempfile::tempdir().expect("temp dir");

        let storage_dir = temp.path().join("cas");
        std::fs::create_dir_all(&storage_dir).expect("cas dir");
        let btree_root = temp.path().join("btree");
        std::fs::create_dir_all(&btree_root).expect("btree dir");
        let manifest_dir = btree_root.join("manifests");
        let idx_dir = btree_root.join("idx");
        std::fs::create_dir_all(&manifest_dir).expect("manifests dir");
        std::fs::create_dir_all(&idx_dir).expect("idx dir");

        let mut config = Config::test_default();
        config.storage_dir = storage_dir.to_string_lossy().to_string();
        config.btree.manifest_dir = manifest_dir.to_string_lossy().to_string();
        config.btree.idx_dir = idx_dir.to_string_lossy().to_string();
        config.port = 0;
        config.min_free_disk_mb = 0;
        config.min_free_disk_pct = 0.0;
        // The CAD workitem is what the cascade removes, so it must be on.
        config.ups.task_producer = true;

        let state = AppState {
            cas: clarus_adapters::storage::ContentAddressedStorage::new(storage_dir)
                .expect("open cas"),
            codec_registry: clarus_adapters::codec::CodecRegistry::new(),
            ups_events: DualEventSink::new(),
            start_time: Instant::now(),
            metrics_ring: Arc::new(StdRwLock::new(std::collections::VecDeque::new())),
            log_buffer: Arc::new(StdRwLock::new(std::collections::VecDeque::new())),
            maintenance: Arc::new(StdRwLock::new(
                clarus_server::state::MaintenanceState::default(),
            )),
            #[cfg(feature = "s3")]
            s3: std::sync::Arc::new(std::sync::OnceLock::new()),
            cold_cas: None,
            shadow: ShadowTier::new(btree_root.join("idx")),
            study_scanner: clarus_core::query::StudyScanner::new(manifest_dir.clone(), idx_dir),
            config: config.clone(),
            workitems_dir: btree_root.join("workitems"),
            commitments_dir: btree_root.join("commitments"),
            transcode_pool: clarus_server::state::TranscodePool::new(32),
            readiness: clarus_server::handlers::readiness::Readiness::new(),
        };

        let listener = std::net::TcpListener::bind("127.0.0.1:0").expect("bind ephemeral port");
        let addr = listener.local_addr().expect("local addr");
        let state = Arc::new(state);
        let shutdown = clarus_core::shutdown::Shutdown::new();
        let sd = shutdown.clone();
        let timeouts = clarus_core::http::conn::Timeouts::from_secs(10, 30, 5, 60);
        let served_state = Arc::clone(&state);
        std::thread::spawn(move || {
            clarus_server::serve::serve(listener, served_state, sd, timeouts, u32::MAX);
        });

        Self {
            addr,
            _temp: temp,
            manifest_dir,
            state,
        }
    }

    fn post(&self, path: &str, content_type: &str, body: &[u8]) -> Response {
        let head = format!(
            "POST {path} HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: {content_type}\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
            body.len()
        );
        let mut request = head.into_bytes();
        request.extend_from_slice(body);
        self.send(&request)
    }

    fn send(&self, request: &[u8]) -> Response {
        let mut stream = TcpStream::connect(self.addr).expect("connect");
        let _ = stream.set_read_timeout(Some(Duration::from_secs(10)));
        stream.write_all(request).expect("write");
        stream.flush().expect("flush");
        let mut buf = Vec::new();
        let _ = stream.read_to_end(&mut buf);
        parse_http(&buf)
    }

    /// Whether a study's manifest is still live (not tombstoned).
    fn study_is_live(&self, study_uid: &str) -> bool {
        self.manifest_dir
            .join(format!("{study_uid}.manifest"))
            .exists()
    }

    /// The workitem file for a study, if it is still present.
    fn workitem_exists(&self, uid: &str) -> bool {
        self.manifest_dir
            .parent()
            .expect("btree root")
            .join("workitems")
            .join(format!("{uid}.cbor"))
            .exists()
    }

    /// Whether a derived object is still referenced by a live manifest.
    ///
    /// The cascade removes objects by rewriting or tombstoning manifests, so
    /// this reads the store the way QIDO does rather than trusting a status
    /// code from the deletion.
    fn instance_is_live(&self, study: &str, series: &str, instance: &str) -> bool {
        let path = self.manifest_dir.join(format!("{study}.manifest"));
        let Ok(manifest) = clarus_core::manifest::read_manifest(&path) else {
            return false;
        };
        manifest.series.iter().any(|s| {
            let series_uid = s
                .attrs
                .iter()
                .find(|(tag, _)| *tag == clarus_core::query::tag::SERIES_INSTANCE_UID)
                .and_then(|(_, v)| match v {
                    clarus_core::manifest::AttrValue::Text(t) => Some(t.as_str()),
                    _ => None,
                });
            if series_uid != Some(series) {
                return false;
            }
            s.instances.iter().any(|i| {
                i.attrs.iter().any(|(tag, v)| {
                    *tag == clarus_core::query::tag::SOP_INSTANCE_UID
                        && matches!(v, clarus_core::manifest::AttrValue::Text(t) if t == instance)
                })
            })
        })
    }

    /// Whether a study's tombstone is still present.
    ///
    /// `study_is_live` and this are complements: a study is either live, or
    /// tombstoned awaiting erase, or gone.
    fn tombstone_exists(&self, study_uid: &str) -> bool {
        self.manifest_dir.join(format!("{study_uid}.del")).exists()
    }

    /// Run the erase worker until its tombstones are drained.
    ///
    /// The erase is a background pass in production; the test drives it
    /// directly so the re-ingest contract can be reached without waiting on a
    /// wall clock. Mirrors the helper `erase_smoke` uses.
    fn drain_erase(&self) {
        // The worker needs the same state the server runs on, so the pass is
        // driven through the public entry point against a fresh handle on the
        // same directories. It is idempotent: a drained store is a no-op.
        let _ = clarus_server::erase_worker::erase_once(&self.state);
        let _ = clarus_server::erase_worker::erase_once(&self.state);
    }

    /// Stow one DICOM file into a study via STOW-RS.
    fn stow(&self, dicom: &[u8]) -> Response {
        let boundary = "clarusDerivedFixtureBoundary";
        let body = multipart_body(boundary, dicom);
        self.post(
            "/dicomweb/studies",
            &format!("multipart/related; type=\"application/dicom\"; boundary={boundary}"),
            &body,
        )
    }

    /// Delete a study through the admin endpoint.
    fn delete_study(&self, study_uid: &str) -> Response {
        let body =
            format!(r#"{{"study_uid":"{study_uid}","reason":"derived-object cascade test"}}"#);
        self.post(
            "/admin/v1/instances/delete",
            "application/json",
            body.as_bytes(),
        )
    }

    /// Delete a series through the admin endpoint.
    fn delete_series(&self, series_uid: &str) -> Response {
        let body =
            format!(r#"{{"series_uid":"{series_uid}","reason":"derived-object cascade test"}}"#);
        self.post(
            "/admin/v1/instances/delete",
            "application/json",
            body.as_bytes(),
        )
    }

    /// Delete one instance through the admin endpoint.
    fn delete_instance(&self, sop_instance_uid: &str) -> Response {
        let body = format!(
            r#"{{"sop_instance_uids":["{sop_instance_uid}"],"reason":"last instance test"}}"#
        );
        self.post(
            "/admin/v1/instances/delete",
            "application/json",
            body.as_bytes(),
        )
    }

    /// Every audit line written so far, concatenated.
    ///
    /// The directory comes from the CONFIG the server actually runs on, not
    /// from a path guessed off the manifest dir: the audit journal is a
    /// sibling that a deployment may relocate, and a test that assumed the
    /// default would silently read an empty directory.
    fn audit_log(&self) -> String {
        let dir = std::path::Path::new(&self.state.config.btree.audit_dir);
        let mut out = String::new();
        if let Ok(entries) = std::fs::read_dir(dir) {
            for entry in entries.flatten() {
                if let Ok(text) = std::fs::read_to_string(entry.path()) {
                    out.push_str(&text);
                }
            }
        }
        out
    }

    /// The `.batch` sidecar text for a study, if present.
    fn batch_sidecar(&self, study_uid: &str) -> Option<String> {
        std::fs::read_to_string(self.manifest_dir.join(format!("{study_uid}.batch"))).ok()
    }
}

fn multipart_body(boundary: &str, dicom: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(format!("--{boundary}\r\n").as_bytes());
    out.extend_from_slice(b"Content-Type: application/dicom\r\n\r\n");
    out.extend_from_slice(dicom);
    out.extend_from_slice(format!("\r\n--{boundary}--\r\n").as_bytes());
    out
}

/// A committed fixture from the test corpus.
fn fixture(name: &str) -> Vec<u8> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join(name);
    std::fs::read(&path).unwrap_or_else(|e| panic!("fixture {} is unreadable: {e}", path.display()))
}

/// Load a derived fixture and rewrite its study/series identity so it can be
/// stowed into the test's own study.
///
/// The committed fixture names a fixed study so the Rust test and the Python
/// generator can be checked against each other. A wire test needs the object
/// inside the study it deletes, so the UIDs are substituted in place: the two
/// study/series/instance UIDs are fixed-length ASCII, so replacing them keeps
/// every length field valid.
fn reidentify(
    mut dicom: Vec<u8>,
    from_study: &str,
    from_series: &str,
    from_instance: &str,
    to_study: &str,
    to_series: &str,
    to_instance: &str,
) -> Vec<u8> {
    for (from, to) in [
        (from_study, to_study),
        (from_series, to_series),
        (from_instance, to_instance),
    ] {
        assert_eq!(
            from.len(),
            to.len(),
            "the substitution must preserve byte length: {from} -> {to}"
        );
        let mut start = 0;
        while let Some(at) = find(&dicom[start..], from.as_bytes()) {
            let abs = start + at;
            dicom[abs..abs + from.len()].copy_from_slice(to.as_bytes());
            start = abs + from.len();
        }
    }
    dicom
}

fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack
        .windows(needle.len())
        .position(|window| window == needle)
}

// -- Response parsing ----------------------------------------------------

struct Response {
    status: u16,
    body: Vec<u8>,
}

impl Response {
    fn assert_status(&self, expected: u16) {
        assert_eq!(
            self.status,
            expected,
            "unexpected status; body: {}",
            String::from_utf8_lossy(&self.body)
        );
    }
}

fn parse_http(buf: &[u8]) -> Response {
    let text = String::from_utf8_lossy(buf);
    let status = text
        .split_whitespace()
        .nth(1)
        .and_then(|s| s.parse().ok())
        .unwrap_or(0);
    let body_start = buf
        .windows(4)
        .position(|w| w == b"\r\n\r\n")
        .map(|at| at + 4)
        .unwrap_or(buf.len());
    let mut body = buf[body_start..].to_vec();
    // Chunked responses: decode so callers see the payload.
    if text
        .to_ascii_lowercase()
        .contains("transfer-encoding: chunked")
        && let Some(decoded) = decode_chunked(&body)
    {
        body = decoded;
    }
    Response { status, body }
}

fn decode_chunked(data: &[u8]) -> Option<Vec<u8>> {
    let mut out = Vec::new();
    let mut pos = 0;
    loop {
        let line_end = find(&data[pos..], b"\r\n")? + pos;
        let size_line = std::str::from_utf8(&data[pos..line_end]).ok()?;
        let size = usize::from_str_radix(size_line.split(';').next()?.trim(), 16).ok()?;
        pos = line_end + 2;
        if size == 0 {
            break;
        }
        out.extend_from_slice(data.get(pos..pos + size)?);
        pos += size + 2;
    }
    Some(out)
}

// -- The three gates -----------------------------------------------------

/// A study deletion takes the workitem named from it, and every derived
/// object that references into it.
#[test]
fn deleting_a_study_removes_its_workitem_and_derived_objects() {
    let srv = TestServer::start();

    // The study itself: an ordinary image, which is not a derived object.
    srv.stow(&fixture("derived_study.dcm")).assert_status(200);
    // A presentation state and a segmentation that reference it.
    srv.stow(&fixture("derived_pr.dcm")).assert_status(200);
    srv.stow(&fixture("derived_seg.dcm")).assert_status(200);

    let wi = workitem_uid(STUDY_A);
    assert!(
        srv.workitem_exists(&wi),
        "stowing a study creates its CAD workitem"
    );

    srv.delete_study(STUDY_A).assert_status(200);

    // The workitem is gone with the study it was named from.
    assert!(
        !srv.workitem_exists(&wi),
        "the derived workitem must go with its study"
    );
}

/// A study deletion claims a derived object that references INTO the deleted
/// study and leaves one that references a DIFFERENT study.
///
/// The study scope used to match "any reference at all", which stayed
/// invisible while the cascade opened manifests by series UID and therefore
/// never found anything. Fixing that read makes the scope rule live, so it is
/// asserted here: two presentation states, one per study, only one of which
/// may go.
#[test]
fn a_study_delete_claims_only_derived_objects_of_that_study() {
    let srv = TestServer::start();
    // Same length as the fixture UIDs: `reidentify` substitutes in place, so
    // every DICOM length field must stay valid.
    let other_study = "1.2.826.0.1.3680043.10.1709.7.1";
    let other_series = "1.2.826.0.1.3680043.10.1709.7.9";
    let other_instance = "1.2.826.0.1.3680043.10.1709.7.1.1";
    // What the unrelated annotation points at: a series of its own study.
    let other_ref_series = "1.2.826.0.1.3680043.10.1709.7.8";
    let other_ref_instance = "1.2.826.0.1.3680043.10.1709.7.1.2";

    // Study A with its own presentation state.
    srv.stow(&fixture("derived_study.dcm")).assert_status(200);
    srv.stow(&fixture("derived_pr.dcm")).assert_status(200);

    // A second study with its own presentation state. The references inside
    // the annotation move too, otherwise the "unrelated" object still
    // annotates study A and the cascade is right to claim it.
    let mut other_pr = fixture("derived_pr.dcm");
    for (from, to) in [
        (REF_SERIES_A, other_ref_series),
        (REF_INSTANCE_A, other_ref_instance),
    ] {
        assert_eq!(from.len(), to.len(), "in-place substitution");
        let mut start = 0;
        while let Some(at) = find(&other_pr[start..], from.as_bytes()) {
            let abs = start + at;
            other_pr[abs..abs + from.len()].copy_from_slice(to.as_bytes());
            start = abs + from.len();
        }
    }
    let other_pr = reidentify(
        other_pr,
        PR_STUDY,
        PR_SERIES,
        PR_INSTANCE,
        other_study,
        other_series,
        other_instance,
    );
    srv.stow(&other_pr).assert_status(200);
    assert!(
        srv.study_is_live(other_study),
        "the second study must be stored"
    );

    srv.delete_study(STUDY_A).assert_status(200);

    assert!(
        srv.study_is_live(other_study),
        "the unrelated study must survive the deletion"
    );
    assert!(
        srv.instance_is_live(other_study, other_series, other_instance),
        "a presentation state of another study must not be claimed by the cascade"
    );
}

/// A series deletion leaves the derived objects of the study's other series
/// alone.
#[test]
fn deleting_a_series_leaves_other_series_derived_objects() {
    let srv = TestServer::start();

    srv.stow(&fixture("derived_study.dcm")).assert_status(200);
    // The PR references series A only.
    srv.stow(&fixture("derived_pr.dcm")).assert_status(200);

    // Deleting series B - which the PR does not reference - must leave the
    // PR and the study in place.
    srv.delete_series(SERIES_B).assert_status(200);

    assert!(
        srv.study_is_live(STUDY_A),
        "deleting one series must not remove the study"
    );
    assert!(
        srv.workitem_exists(&workitem_uid(STUDY_A)),
        "deleting one series must not remove the study workitem"
    );
}

/// Re-stowing a deleted study recreates its workitem.
///
/// A deleted study refuses a re-stow until its erase has drained - that is
/// the existing contract, covered by `erase_smoke`, and this test does not
/// restate it. What is checked here is the cascade's share of the round trip:
/// once the study is back, the workitem is back with it. The workitem is
/// created fire-and-forget on the STOW path, so a cascade that removed it
/// without the create path recreating it would leave the study permanently
/// without its CAD step.
#[test]
fn re_stowing_a_deleted_study_recreates_its_workitem() {
    let srv = TestServer::start();

    srv.stow(&fixture("derived_study.dcm")).assert_status(200);
    let wi = workitem_uid(STUDY_A);
    assert!(srv.workitem_exists(&wi), "first stow creates the workitem");

    srv.delete_study(STUDY_A).assert_status(200);
    assert!(!srv.workitem_exists(&wi), "the delete removes it");

    // The erase must drain before the study UID is free again (existing
    // behaviour); the cascade does not change that.
    srv.drain_erase();
    assert!(
        !srv.tombstone_exists(STUDY_A),
        "the erase lifts the tombstone"
    );

    // The same study arrives again: it is stored, and so is its workitem.
    srv.stow(&fixture("derived_study.dcm")).assert_status(200);
    assert!(srv.study_is_live(STUDY_A), "re-ingest recreates the study");
    assert!(
        srv.workitem_exists(&wi),
        "a re-stowed study gets its workitem back"
    );
}

/// The substitution helper is what lets these tests place a fixture in their
/// own study, so its contract is checked directly.
#[test]
fn reidentification_preserves_lengths() {
    let original = fixture("derived_pr.dcm");
    let changed = reidentify(
        original.clone(),
        "1.2.826.0.1.3680043.10.1709.1.1",
        "1.2.826.0.1.3680043.10.1709.1.1.1",
        "1.2.826.0.1.3680043.10.1709.1.1",
        "1.2.826.0.1.3680043.10.1709.1.9",
        "1.2.826.0.1.3680043.10.1709.1.9.1",
        "1.2.826.0.1.3680043.10.1709.1.9",
    );
    assert_eq!(
        original.len(),
        changed.len(),
        "the file size must not change"
    );
    assert_ne!(original, changed, "the substitution must have happened");
}

/// The live-study guard the cascade relies on: a manifest is present until it
/// is tombstoned.
#[test]
fn a_stored_study_has_a_live_manifest() {
    let srv = TestServer::start();
    srv.stow(&fixture("derived_study.dcm")).assert_status(200);
    assert!(srv.study_is_live(STUDY_A));
    srv.delete_study(STUDY_A).assert_status(200);
    assert!(
        !srv.study_is_live(STUDY_A),
        "the manifest is tombstoned by the delete"
    );
}

/// R2: deleting the LAST INSTANCE of a study must tombstone it the way a
/// study deletion does.
///
/// The last-instance branch did a bare `rename` to `.del`. Three things a
/// study deletion does were skipped, and each has a consequence:
///
/// - no `AuditEvent::Delete`: the deletion became invisible in the journal,
///   and no `erase_complete` row could ever close it;
/// - no `.batch` sidecar: the erase-worker had no batch id to report;
/// - no `study_scanner.on_study_erased`: the RAM index kept serving a study
///   that no longer exists on disk.
///
/// Deleting an annotated study almost always takes this branch, because the
/// annotation is the study's only remaining instance once the image is gone.
#[test]
fn deleting_the_last_instance_tombstones_the_study_with_audit_index_and_sidecar() {
    let srv = TestServer::start();

    // A study holding exactly ONE instance: deleting it is the last-instance
    // path, and the study must leave the store the way a study deletion takes
    // it. The alternative - an empty manifest left behind - is a ghost: QIDO
    // keeps answering for a study that holds nothing, and no erase-worker
    // tombstone ever reclaims its blobs.
    //
    // The UIDs are the same LENGTH as the fixture's, because `reidentify`
    // substitutes in place and every DICOM length field must stay valid.
    let study = "1.2.826.0.1.3680043.10.1709.8"; // 29, like STUDY_A
    let series = "1.2.826.0.1.3680043.10.1709.8.1"; // 31, like REF_SERIES_A
    let instance = "1.2.826.0.1.3680043.10.1709.8.1.1"; // 33, like REF_INSTANCE_A

    let image = reidentify(
        fixture("derived_study.dcm"),
        STUDY_A,
        REF_SERIES_A,
        REF_INSTANCE_A,
        study,
        series,
        instance,
    );
    srv.stow(&image).assert_status(200);
    assert!(srv.study_is_live(study), "the study holds its one instance");

    srv.delete_instance(instance).assert_status(200);

    // 1. The study is tombstoned, not merely emptied.
    assert!(
        srv.tombstone_exists(study),
        "the last instance must leave a tombstone, exactly like a study delete"
    );
    assert!(
        !srv.study_is_live(study),
        "the live manifest is gone, so QIDO cannot serve the study"
    );
    // 2. The audit journal records the study tombstone. The sidecar names the
    //    batch that must be closed, so the row is found by the STUDY target
    //    and the sidecar must agree with THAT row.
    let log = srv.audit_log();
    let sidecar = srv
        .batch_sidecar(study)
        .expect("a .batch sidecar naming the erase batch");
    let batch = sidecar.trim().to_string();
    let study_row = log
        .lines()
        .find(|l| {
            l.contains("\"event\":\"delete\"")
                && l.contains(&format!("\"target\":\"{study}\""))
                && l.contains(&format!("\"batch_id\":\"{batch}\""))
        })
        .unwrap_or_else(|| panic!("no delete row names study {study} under batch {batch}: {log}"));
    assert!(
        study_row.contains("\"patient_id\":\"DERIVED-STUDY-1\""),
        "the study row carries the patient identity: {study_row}"
    );

    // 3. And the erase runs to completion, which is what the sidecar is for:
    //    `erase_complete` must name the same batch the study row did.
    srv.drain_erase();
    let log = srv.audit_log();
    assert!(
        log.contains(&format!(
            "\"event\":\"erase_complete\",\"batch_id\":\"{batch}\""
        )),
        "the erase closes batch {batch} with erase_complete: {log}"
    );
    assert!(
        !srv.tombstone_exists(study),
        "the tombstone is lifted once erased"
    );
}

/// R2, second path: the CASCADE must tombstone a study it empties.
///
/// `remove_derived_object` rewrites the owning study's manifest as it removes
/// a derived object. When the removed object is the study's LAST instance the
/// old code did a bare `rename` to `.del` - no audit row, no `.batch`
/// sidecar, and no `on_study_erased` - so the journal could never close the
/// erase and QIDO kept serving the study from the RAM index. A study that is
/// emptied by the cascade must leave exactly the way one emptied by a study
/// deletion does.
#[test]
fn deleting_the_last_derived_object_tombstones_its_study() {
    let srv = TestServer::start();

    // A study whose ONLY instance is a derived object. It cannot be created
    // by STOW-ing a presentation state alone (a PR needs a referenced image
    // to be stowed), so the reference fixture is stowed into a DIFFERENT
    // study and the PR is re-pointed at a study of its own.
    let host_study = "1.2.826.0.1.3680043.10.1709.9"; // 29, like STUDY_A
    let host_series = "1.2.826.0.1.3680043.10.1709.9.1"; // 31, like REF_SERIES_A
    let host_instance = "1.2.826.0.1.3680043.10.1709.9.1.1"; // 33, like REF_INSTANCE_A

    let image = reidentify(
        fixture("derived_study.dcm"),
        STUDY_A,
        REF_SERIES_A,
        REF_INSTANCE_A,
        host_study,
        host_series,
        host_instance,
    );
    srv.stow(&image).assert_status(200);

    // The annotation keeps its OWN study (`PR_STUDY`), which therefore holds
    // exactly one instance: the presentation state itself. Its REFERENCES
    // must point into the host study, or the cascade has no reason to claim
    // it and this test would be asserting on a removal that never happens.
    let mut pr = fixture("derived_pr.dcm");
    for (from, to) in [(REF_SERIES_A, host_series), (REF_INSTANCE_A, host_instance)] {
        assert_eq!(from.len(), to.len(), "in-place substitution");
        let mut start = 0;
        while let Some(at) = find(&pr[start..], from.as_bytes()) {
            let abs = start + at;
            pr[abs..abs + from.len()].copy_from_slice(to.as_bytes());
            start = abs + from.len();
        }
    }
    srv.stow(&pr).assert_status(200);
    assert!(
        srv.study_is_live(PR_STUDY),
        "the annotation's study holds its one instance"
    );

    // Deleting the host study cascades: the PR references into it and is
    // removed. That removal empties PR_STUDY, which must then be tombstoned.
    srv.delete_study(host_study).assert_status(200);

    assert!(
        srv.tombstone_exists(PR_STUDY),
        "the cascade must tombstone a study it empties, not leave a bare rename"
    );
    assert!(
        !srv.study_is_live(PR_STUDY),
        "the emptied study is gone from the live set"
    );
    let sidecar = srv
        .batch_sidecar(PR_STUDY)
        .expect("the cascade writes a .batch sidecar for the study it empties");
    let batch = sidecar.trim().to_string();
    let log = srv.audit_log();
    assert!(
        log.lines().any(|l| l.contains("\"event\":\"delete\"")
            && l.contains(&format!("\"target\":\"{PR_STUDY}\""))
            && l.contains(&format!("\"batch_id\":\"{batch}\""))),
        "the cascade's study tombstone is in the journal under batch {batch}: {log}"
    );
}

/// R2, third path: the SERIES delete must tombstone a study it empties.
///
/// `delete_series_manifest` used to rewrite the manifest unconditionally and
/// return, so deleting a study's only series left an empty but LIVE
/// `{study}.manifest`: QIDO kept answering for a study with nothing in it and
/// no erase-worker tombstone existed to reclaim its blobs. The instance path
/// was fixed first; the two paths must share one terminal state or they drift
/// apart again, so both now call the same helper.
#[test]
fn deleting_the_only_series_tombstones_its_study() {
    let srv = TestServer::start();

    // One instance in one series - the fixture's own study, untouched.
    let image = fixture("derived_study.dcm");
    srv.stow(&image).assert_status(200);
    assert!(srv.study_is_live(STUDY_A), "the study holds its one series");

    srv.delete_series(REF_SERIES_A).assert_status(200);

    assert!(
        srv.tombstone_exists(STUDY_A),
        "deleting the only series must leave a tombstone, like a study delete"
    );
    assert!(
        !srv.study_is_live(STUDY_A),
        "the live manifest is gone, so QIDO cannot serve the emptied study"
    );
    let sidecar = srv
        .batch_sidecar(STUDY_A)
        .expect("a .batch sidecar naming the erase batch");
    let batch = sidecar.trim().to_string();
    let log = srv.audit_log();
    assert!(
        log.lines().any(|l| l.contains("\"event\":\"delete\"")
            && l.contains(&format!("\"target\":\"{STUDY_A}\""))
            && l.contains(&format!("\"batch_id\":\"{batch}\""))),
        "the study tombstone is in the journal under batch {batch}: {log}"
    );
}
