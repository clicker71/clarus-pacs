def _strip_module_docstring(lines):
    """Strip the module-level docstring (first triple-quoted string) from a list of lines.

    Returns the lines with the docstring removed.
    """
    if not lines:
        return lines

    # Find the start of a triple-quoted docstring
    in_docstring = False
    docstring_delim = None
    result = []
    docstring_start = -1
    docstring_end = -1

    for i, line in enumerate(lines):
        stripped = line.strip()
        if not in_docstring:
            # Check for triple-quoted docstring start (must be at beginning of module)
            if stripped.startswith('"""') or stripped.startswith("'''"):
                in_docstring = True
                docstring_delim = stripped[:3]
                docstring_start = i
                # Check if it's a single-line docstring
                if stripped.count(docstring_delim) >= 2 and len(stripped) > 3:
                    in_docstring = False
                    docstring_end = i
                    continue
                continue
            else:
                # First non-docstring, non-blank, non-comment line ??? docstring not found
                if stripped and not stripped.startswith('#'):
                    # No module docstring
                    return lines
                result.append(line)
        else:
            # Inside docstring ??? look for closing delimiter
            if docstring_delim in stripped:
                in_docstring = False
                docstring_end = i
                continue
            # Skip docstring content lines

    if docstring_start >= 0:
        # Return everything after the docstring
        return lines[docstring_end + 1:] if docstring_end >= 0 else lines

    return lines


def _strip_imports(lines):
    """Remove 'from clean_code.' and 'from .' imports (including multi-line).

    Handles:
        from clean_code import VERSION
        from clean_code.xxx import YYY
        from clean_code.xxx import (
            YYY,
            ZZZ,
        )
        from .xxx import YYY
        from clean_code.xxx import YYY, \\
            ZZZ
    """
    result = []
    in_stripped_import = False
    paren_depth = 0
    in_backslash_continuation = False

    def _is_inter_module_import(line):
        """Check if a line starts an inter-module import that should be stripped."""
        s = line.strip()
        return (s.startswith("from clarus_bridge ") or
                s.startswith("from clarus_bridge.") or
                s.startswith("from clean_code ") or
                s.startswith("from clean_code.") or
                s.startswith("from ."))

    for line in lines:
        stripped = line.strip()

        if in_stripped_import:
            # Track parentheses depth to find end of multi-line import
            paren_depth += stripped.count('(') - stripped.count(')')
            if paren_depth <= 0:
                # For backslash continuations, only exit if this line
                # doesn't end with a continuation backslash
                if not in_backslash_continuation or not stripped.endswith('\\'):
                    in_stripped_import = False
                    in_backslash_continuation = False
                    paren_depth = 0
            else:
                # Inside parens ??? not a backslash-only continuation
                in_backslash_continuation = False
            continue

        if _is_inter_module_import(stripped):
            # Check if this is a multi-line import
            if '(' in stripped and ')' not in stripped:
                in_stripped_import = True
                paren_depth = 1
                in_backslash_continuation = False
            elif stripped.endswith('\\'):
                # Line continuation with backslash
                in_stripped_import = True
                paren_depth = 0
                in_backslash_continuation = True
            # Single-line import ??? skip it
            continue

        result.append(line)

    # Post-process: remove blank lines left after stripping imports
    cleaned = []
    prev_blank = False
    for line in result:
        is_blank = line.strip() == ''
        if is_blank and prev_blank:
            continue
        cleaned.append(line)
        prev_blank = is_blank
    return cleaned


def _strip_header_lines(lines):
    """Strip copyright, pyright suppression, and shebang lines from individual modules.
    
    These are included once at the top of the bundled output by the HEADER template.
    Individual modules should not duplicate them.
    """
    result = []
    for line in lines:
        stripped = line.strip()
        if (stripped.startswith('# Copyright') or
            stripped.startswith('# pyright:') or
            stripped.startswith('#!/usr/bin/env')):
            continue
        result.append(line)
    return result


def _check_duplicate_definitions(all_lines):
    """Detect duplicate top-level definitions that silently shadow in bundle.

    Scans the concatenated output for:
    - def name(  ??? function definitions
    - class Name( ??? class definitions
    - NAME = {   ??? dict/list/set constants (common for lookup tables)
    - NAME =      ??? top-level assignments (only inside #--- section blocks)

    Returns dict[name ??? list of line numbers]. Empty dict = clean.
    """
    dup_map = {}  # name -> [line_num, ...]
    # Regex: match def/class/assignment at start of line (top-level)
    # We only care about names that appear in section blocks, not inside functions.
    def_re = re.compile(r'^(def\s+)([a-zA-Z_][a-zA-Z0-9_]*)\s*\(')
    class_re = re.compile(r'^(class\s+)([a-zA-Z_][a-zA-Z0-9_]*)\s*[:\(]')
    # Top-level constant assignments: NAME = value  (not indented)
    assign_re = re.compile(r'^([A-Z_][A-Z0-9_]*)\s*=\s*[\[\{\(]')

    for i, line in enumerate(all_lines):
        line_num = i + 1  # 1-indexed for human readability

        m = def_re.match(line)
        if m:
            name = m.group(2)
            dup_map.setdefault(name, []).append(line_num)
            continue

        m = class_re.match(line)
        if m:
            name = m.group(2)
            dup_map.setdefault(name, []).append(line_num)
            continue

        m = assign_re.match(line)
        if m:
            name = m.group(1)
            dup_map.setdefault(name, []).append(line_num)
            continue

    # Keep only names that appear 2+ times
    return {k: v for k, v in dup_map.items() if len(v) >= 2}


def bundle(version, output_path):
    """Assemble single-file clbridge.py from clean_code/ modules."""
    # Find the base directory (parent of this script = clbridge/)
    base_dir = os.path.dirname(os.path.abspath(__file__))

    all_lines = []

    # Write header
    header = HEADER.format(VERSION=version)
    all_lines.extend(header.splitlines(keepends=True))

    # Short revision this bundle was cut from, reported by `GET /version`.
    # Rewritten in the concatenated output below; a bundle generated outside a
    # repository keeps the source placeholder.
    stamp = _git_rev()
    print(f'Bundle stamp: {stamp}', file=sys.stderr)

    # BR-001: Auto-compute module order from imports
    clean_dir = os.path.join(base_dir, 'clean_code')
    print('Computing module order from imports...', file=sys.stderr)
    order = compute_order(clean_dir)
    for name, rel_path in order:
        print(f'    {name} <- {rel_path}', file=sys.stderr)
    
    for name, rel_path in order:
        # Skip build-time modules (not runtime code)
        if name == '_bundle_order':
            continue
        full_path = os.path.join(clean_dir, rel_path)

        with open(full_path, "r", encoding="utf-8-sig") as f:
            lines = f.readlines()

        # Strip copyright/pyright/shebang (included once in HEADER)
        lines = _strip_header_lines(lines)
        # Strip module docstring
        lines = _strip_module_docstring(lines)
        # Strip inter-module imports
        lines = _strip_imports(lines)

        # Add section comment
        section = name.replace('clean_code.', '').replace('.', '/')
        all_lines.append('# ---------------------------------------------------------------------------\n')
        all_lines.append(f'# Bridge: {section}\n')
        all_lines.append('# ---------------------------------------------------------------------------\n')

        all_lines.extend(lines)
        # Add a blank line between modules
        if lines and not lines[-1].endswith('\n'):
            all_lines.append('\n')
        all_lines.append('\n')

    # Inject the stamp into the bundled copy of the constant. The source
    # placeholder is a single literal line; the bundle carries the real
    # revision.
    for i, line in enumerate(all_lines):
        if line.startswith('BUNDLE_STAMP ='):
            all_lines[i] = f'BUNDLE_STAMP = "{stamp}"\n'
            break
    else:
        print('ERROR: BUNDLE_STAMP not found in clean_code/ - cannot stamp bundle.',
              file=sys.stderr)
        sys.exit(1)

    with open(output_path, "w", encoding="utf-8") as out:
        out.writelines(all_lines)

    # Verify: file not truncated (locked by running process?)
    if os.path.getsize(output_path) < 1000:
        print(f"ERROR: {output_path} is too small ({os.path.getsize(output_path)} bytes). "
              "File may be locked by a running bridge process. Kill it first.",
              file=sys.stderr)
        sys.exit(1)

    # Verify: bundle compiles
    try:
        py_compile.compile(output_path, doraise=True)
    except py_compile.PyCompileError as e:
        print(f"ERROR: bundle failed syntax check: {e}", file=sys.stderr)
        sys.exit(1)

    # Verify: bundle integrity ??? critical for air-gapped deployment
    with open(output_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # ?????? DUPLICATE DEFINITION DETECTION ?????????????????????????????????????????????????????????????????????????????????????????????
    # In a concatenated bundle, duplicate `def` or top-level `NAME =`
    # means the SECOND silently shadows the FIRST. This is almost
    # always a bug ??? the first module's version is lost.
    # Underscore-prefixed names (_private) in multiple modules
    # are especially suspicious: they signal "module-private API"
    # that accidentally collides when concatenated.
    _dup_defs = _check_duplicate_definitions(all_lines)
    if _dup_defs:
        print(f"\n???  DUPLICATE DEFINITIONS ({len(_dup_defs)} names):", file=sys.stderr)
        print("   Second definition SHADOWS the first in concatenated bundle.", file=sys.stderr)
        for name, occurrences in sorted(_dup_defs.items()):
            lines_str = ", ".join(f"line {ln}" for ln in occurrences)
            severity = "ERROR" if name.startswith('_') else "WARNING"
            marker = "????" if name.startswith('_') else "????"
            print(f"   {marker} [{severity}] {name}: {lines_str}", file=sys.stderr)
        # Fail on private-name duplicates (underscore prefix = module-private)
        private_dups = [n for n in _dup_defs if n.startswith('_')]
        if private_dups:
            print(f"\n??? BUNDLE FAILED: {len(private_dups)} private name(s) duplicated.", file=sys.stderr)
            print("   Move the shared definition to a common module (e.g. protocol.py)", file=sys.stderr)
            print("   and import it from both modules.", file=sys.stderr)
            sys.exit(1)

    # Check 1: _http_status_to_dimse is used (not old hardcoded mapping)
    assert '_http_status_to_dimse(resp.status_code)' in content, \
        "BUNDLE INTEGRITY: _http_status_to_dimse not found ??? old stow_single_instance?"

    # Check 2: OutboxQueue is present
    assert 'class OutboxQueue' in content, \
        "BUNDLE INTEGRITY: OutboxQueue not found ??? old code path?"

    # Check 3: stow_single_instance present (not removed with stow_batch)
    assert 'def stow_single_instance' in content, \
        "BUNDLE INTEGRITY: stow_single_instance not found"

    # Check 4: stow_batch_instances PRESENT ??? fieldtest 22.08: 1063 one-POST-
    # per-slice spams ACCESS and costs a full server STOW cycle per instance.
    # Batching several SOPs of one study into a single multipart POST keeps the
    # request count proportional to studies rather than instances.
    assert 'def stow_batch_instances' in content, \
        "BUNDLE INTEGRITY: stow_batch_instances not found (outbox batching)"

    # Check 5: _auth_headers REMOVED ??? auth is nginx responsibility
    assert '_auth_headers' not in content, \
        "BUNDLE INTEGRITY: _auth_headers should be REMOVED (auth is nginx responsibility)"

    # Check 6: config section renamed [clarus] ??? [dicomweb]
    assert 'config.get("dicomweb"' in content or '[dicomweb]' in content.lower(), \
        "BUNDLE INTEGRITY: [dicomweb] section not found ??? old [clarus]?"

    # Check 7: auto-registration REMOVED (security: blind AE trust is a hole)
    # Note: register_scp and auto_registered removed in P7 SharedDb refactor.
    assert 'def register_scp' not in content, \
        "BUNDLE INTEGRITY: register_scp should be REMOVED (auto-registration deleted)"
    assert 'auto_registered' not in content, \
        "BUNDLE INTEGRITY: auto_registered should be REMOVED"

    # Check 8: peers are loaded lazily on C-MOVE (lookup_scp + reload_peers_from_file)
    assert 'def register_peer' in content, \
        "BUNDLE INTEGRITY: register_peer must be PRESENT (peers.conf registration)"
    assert 'def lookup_scp' in content, \
        "BUNDLE INTEGRITY: lookup_scp must be PRESENT (peer lookup)"
    assert 'def reload_peers_from_file' in content, \
        "BUNDLE INTEGRITY: reload_peers_from_file must be PRESENT (peers.conf reload)"

    # Check 9: the stamp injection actually landed. A bundle that still carries
    # the source placeholder cannot identify itself over GET /version, which is
    # the whole point of the stamp.
    assert f'BUNDLE_STAMP = "{stamp}"' in content, \
        "BUNDLE INTEGRITY: BUNDLE_STAMP was not injected with the git revision"

    print(f"Bundled {output_path} ({len(all_lines)} lines) from {len(order)} modules")


if __name__ == "__main__":
    version = sys.argv[1] if len(sys.argv) > 1 else "0.3.1-beta"
    # Always write to the script's own directory, not CWD
    base_dir = os.path.dirname(os.path.abspath(__file__))
    default_output = os.path.join(base_dir, "clbridge.py")
    output = sys.argv[2] if len(sys.argv) > 2 else default_output
    bundle(version, output)

