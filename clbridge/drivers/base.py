"""Abstract base for C-PRINT drivers (PS3.4 §H)."""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Optional

if TYPE_CHECKING:
    from pydicom import Dataset


@dataclass
class PrintResult:
    """Result of a print job.

    Attributes:
        job_id: Unique job identifier (generated by driver).
        status: DICOM Print status — 0x0000 (Success), 0xB600 (Film session error),
                0xB601 (Film box error), 0xB602 (Image box error), 0xB603 (Print failure),
                0xC200 (Generic error).
        film_boxes_printed: Number of film boxes successfully printed.
        failed_images: List of (image_index, error_reason) for failed images.
        printer_message: Optional status info string from printer N-ACTION-RSP.
    """

    job_id: str
    status: int
    film_boxes_printed: int
    failed_images: list = field(default_factory=list)
    printer_message: Optional[str] = None

    @property
    def is_success(self) -> bool:
        return self.status == 0x0000


class AbstractPrintDriver(ABC):
    """Abstract DICOM Print driver (PS3.4 §H).

    Subclasses implement the DIMSE N-CREATE/N-SET/N-ACTION/N-DELETE
    sequence to a specific printer type.
    """

    @abstractmethod
    def print(
        self,
        film_session: "Dataset",
        images: list[bytes],
        printer_host: str,
        printer_port: int,
        calling_aet: str,
        called_aet: str | None = None,
    ) -> PrintResult:
        """Execute a DICOM Print job.

        Args:
            film_session: pydicom Dataset containing Film Session attributes
                (e.g. NumberOfCopies, PrintPriority, MediumType, FilmDestination,
                 FilmOrientation, FilmSizeID, etc. — see PS3.4 §H.2.2).
            images: List of raw DICOM Part 10 byte strings — one per Image Box.
            printer_host: IP/hostname of the DICOM printer (Print SCP).
            printer_port: TCP port of the DICOM printer.
            calling_aet: AE Title to use when calling the printer (SCU).
            called_aet: The PRINTER's AE Title (PS3.8 9.3.2.1). Defaults to
                `calling_aet` only for a peer that accepts any Called AE.

        Returns:
            PrintResult with job status, counts, and error details.
        """
        ...

    @abstractmethod
    def driver_name(self) -> str:
        """Human-readable driver name for logging."""
        ...
